export function calcularNumeroVida(fechaNacimiento: string): number {
  if (!fechaNacimiento) return 1
  const digitos = fechaNacimiento.replace(/-/g, '').split('').map(Number)
  let suma = digitos.reduce((a, b) => a + b, 0)

  const reducir = (n: number): number => {
    if (n === 11 || n === 22 || n === 33) return n
    if (n < 10) return n
    return reducir(n.toString().split('').reduce((a, b) => a + parseInt(b), 0))
  }

  return reducir(suma)
}