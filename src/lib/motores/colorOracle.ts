export function getColorDelDia(): keyof typeof COLORES {
  const hoy = new Date()
  const semilla = hoy.getFullYear() * 10000 + (hoy.getMonth() + 1) * 100 + hoy.getDate()
  const colores = Object.keys(COLORES) as Array<keyof typeof COLORES>
  return colores[semilla % colores.length]
}

export function getColorAleatorio(): keyof typeof COLORES {
  const colores = Object.keys(COLORES) as Array<keyof typeof COLORES>
  return colores[Math.floor(Math.random() * colores.length)]
}