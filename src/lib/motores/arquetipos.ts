export function calcularArquetipo(respuestas: number[]): typeof ARQUETIPOS[0] {
  const puntuacion: Record<string, number> = {}
  ARQUETIPOS.forEach(a => { puntuacion[a.id] = 0 })

  respuestas.forEach((respuestaIdx, preguntaIdx) => {
    const pregunta = PREGUNTAS_TEST[preguntaIdx]
    if (pregunta && pregunta.opciones[respuestaIdx]) {
      pregunta.opciones[respuestaIdx].arquetipos.forEach(id => {
        puntuacion[id] = (puntuacion[id] || 0) + 1
      })
    }
  })

  const ganador = Object.entries(puntuacion).sort((a, b) => b[1] - a[1])[0][0]
  return ARQUETIPOS.find(a => a.id === ganador) || ARQUETIPOS[0]
}

