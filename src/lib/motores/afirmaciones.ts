export function getAfirmacionDelDia(signo: string): string {
  const hoy = new Date()
  const semilla = hoy.getFullYear() * 10000 + (hoy.getMonth() + 1) * 100 + hoy.getDate()
  const lista = AFIRMACIONES[signo] || AFIRMACIONES['Universal']
  return lista[semilla % lista.length]
}

export function getAfirmacionTematica(tema: keyof typeof AFIRMACIONES_TEMATICAS): string {
  const hoy = new Date()
  const semilla = hoy.getFullYear() * 10000 + (hoy.getMonth() + 1) * 100 + hoy.getDate()
  const lista = AFIRMACIONES_TEMATICAS[tema]
  return lista[semilla % lista.length]
}