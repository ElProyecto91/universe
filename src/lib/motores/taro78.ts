export function cartaAleatoriaMenor() {
  const palos = Object.keys(ARCANOS_MENORES) as Array<keyof typeof ARCANOS_MENORES>
  const palo = palos[Math.floor(Math.random() * palos.length)]
  const cartas = ARCANOS_MENORES[palo]
  const carta = cartas[Math.floor(Math.random() * cartas.length)]
  return { ...carta, palo, invertida: Math.random() > 0.7 }
}